/** 解説の差し込み記号 → 「50〜70%」のような表記 */
function skt_rate_tokens() {
    $rates = skt_sanitize_rates(skt_opt('rates'));
    $map = array();
    foreach ($rates as $k => $r) {
        $lo = rtrim(rtrim(number_format($r['lo'], 1, '.', ''), '0'), '.');
        $hi = rtrim(rtrim(number_format($r['hi'], 1, '.', ''), '0'), '.');
        $map['{' . $k . '}'] = $lo === $hi ? $lo . '%' : $lo . '〜' . $hi . '%';
    }
    return $map;
}

